/// Whether RustGIS 0.5.0 knows `code` (as `Crs::from_epsg` does, with its Web Mercator aliases).
pub fn known(code: u32) -> bool {
    if matches!(code, 4326 | 3857 | 3785 | 900_913 | 102_100 | 102_113) {
        return true;
    }
    let Ok(c) = u16::try_from(code) else { return false };
    match RUNS.binary_search_by(|&(a, b)| if b < c { std::cmp::Ordering::Less } else if a > c { std::cmp::Ordering::Greater } else { std::cmp::Ordering::Equal }) {
        Ok(_) => true,
        Err(_) => false,
    }
}

