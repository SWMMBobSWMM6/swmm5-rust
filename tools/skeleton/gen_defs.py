#!/usr/bin/env python3
"""Translate EPA SWMM's object-like #defines and enums into Rust consts.

  gen_defs.py SOLVER_DIR OUT_DIR

consts.rs   numeric #defines of the shared headers (int -> i32, else f64)
enums.rs    every enum of the shared headers, constants as i32 (C enums are int)
text.rs     the string #defines of text.h (byte strings, exactly as C sees them)
"""
import re, sys, os
D, O = sys.argv[1], sys.argv[2]

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', ' ', s, flags=re.S)
    out = []
    for line in s.split('\n'):
        # remove // comments not inside strings
        res, ins, i = '', False, 0
        while i < len(line):
            c = line[i]
            if c == '"' and (i == 0 or line[i-1] != '\\'): ins = not ins
            if not ins and line.startswith('//', i): break
            res += c; i += 1
        out.append(res)
    return '\n'.join(out)

def defines(path):
    s = strip_comments(open(path, encoding='latin-1').read())
    s = s.replace('\\\n', ' ')
    for m in re.finditer(r'^[ \t]*#[ \t]*define[ \t]+(\w+)(?!\()[ \t]+(.+?)[ \t]*$', s, flags=re.M):
        yield m.group(1), m.group(2).strip()

def rust_bytes(cstrs):
    # concatenate C string literals into one Rust byte string, keeping escapes
    body = ''.join(cstrs)
    body = body.replace('\\"', '"').replace('"', '\\"')
    return 'b"' + body + '"'

skip = {'CONSTS_H', 'DATETIME_H', 'TEXT_H', 'ERROR_H', 'ENUMS_H', 'KEYWORDS_H', 'MACROS_H', 'OBJECTS_H',
        'GLOBALS_H', 'FUNCS_H', 'HEADERS_H', 'INFIL_H', 'EXFIL_H', 'LID_H', 'INLET_H', 'STREET_H',
        'MATHEXPR_H', 'HASH_H', 'MEMPOOL_H', 'ODESOLVE_H', 'FINDROOT_H', 'EXTERN', 'DLLEXPORT', 'WINDOWS'}
nums, texts = [], []
for h in ['consts.h', 'datetime.h', 'objects.h', 'infil.h', 'exfil.h', 'lid.h', 'inlet.h', 'street.h', 'hash.h', 'mathexpr.h', 'enums.h', 'error.h', 'keywords.h']:
    for n, v in defines(os.path.join(D, h)):
        if n in skip: continue
        v0 = v
        if re.fullmatch(r'-?0x[0-9A-Fa-f]+', v) or re.fullmatch(r'-?\d+L?', v):
            nums.append((n, 'i32', str(int(v.rstrip('L'), 0)), h))
        elif re.fullmatch(r'-?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?', v):
            vv = v if ('.' in v or 'e' in v.lower()) else v + '.0'
            vv = re.sub(r'^(-?)\.', r'\g<1>0.', vv)
            vv = re.sub(r'(\d)\.([eE])', r'\1.0\2', vv)
            vv = re.sub(r'(\d)\.$', r'\1.0', vv)
            nums.append((n, 'f64', vv, h))
        elif v.startswith('"'):
            nums.append((n, '&[u8]', rust_bytes(re.findall(r'"((?:[^"\\]|\\.)*)"', v)), h))
        else:
            nums.append((n, '?', v0, h))
with open(os.path.join(O, 'consts.rs'), 'w') as f:
    f.write('//! The constants of consts.h, datetime.h and the other shared headers\n'
            '//! (generated by tools/skeleton/gen_defs.py). An integer #define is i32 and\n'
            '//! a floating one f64, as C types the literal; where C mixes an int constant\n'
            '//! into double arithmetic the Rust code writes `as f64` at that spot.\n\n')
    seen = set()
    for n, t, v, h in nums:
        if n in seen: continue
        seen.add(n)
        if t == '?':
            f.write(f'// {h}: #define {n} {v}  (translated by hand below)\n')
        else:
            f.write(f'pub const {n}: {t} = {v};\n')

# enums
enums_out = []
for h in ['enums.h', 'error.h', 'objects.h', 'datetime.h', 'infil.h', 'exfil.h', 'lid.h', 'inlet.h', 'street.h', 'mathexpr.h', 'keywords.h', 'text.h']:
    s = strip_comments(open(os.path.join(D, h), encoding='latin-1').read())
    for m in re.finditer(r'(?:typedef\s+)?enum\s*(\w*)\s*\{(.*?)\}\s*(\w*)\s*;', s, flags=re.S):
        tag, body, tname = m.group(1), m.group(2), m.group(3)
        val = -1
        items = []
        for it in [x.strip() for x in body.split(',') if x.strip()]:
            if '=' in it:
                k, e = [x.strip() for x in it.split('=', 1)]
                try:
                    val = int(e, 0)
                except ValueError:
                    known = {a: b for a, b in items}
                    val = eval(e, {}, known)
            else:
                k = it; val += 1
            items.append((k, val))
        enums_out.append((h, tname or tag, items))
with open(os.path.join(O, 'enums.rs'), 'w') as f:
    f.write('//! Every enum of enums.h and the other shared headers, as i32 constants\n'
            '//! (generated by tools/skeleton/gen_defs.py). C enums are ints and SWMM\n'
            '//! stores them in int fields and compares them with ints, so they stay so.\n\n')
    seen = set()
    for h, name, items in enums_out:
        f.write(f'// {h}: {name}\n')
        for k, v in items:
            if k in seen:
                f.write(f'// (duplicate) {k} = {v}\n'); continue
            seen.add(k)
            f.write(f'pub const {k}: i32 = {v};\n')
        f.write('\n')

# text.h
with open(os.path.join(O, 'text.rs'), 'w') as f:
    f.write('//! The text of text.h, byte for byte (generated by tools/skeleton/gen_defs.py).\n\n')
    done = set()
    for n, v in defines(os.path.join(D, 'text.h')):
        if n in skip or n in done: continue
        done.add(n)
        lits = re.findall(r'"((?:[^"\\]|\\.)*)"', v)
        if lits:
            f.write(f'pub const {n}: &[u8] = {rust_bytes(lits)};\n')
        else:
            f.write(f'// #define {n} {v}\n')
print('ok')
