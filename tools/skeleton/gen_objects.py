#!/usr/bin/env python3
"""Shared SWMM data types (objects.h, infil.h, exfil.h, lid.h) as safe Rust.

Field names, order and scalar types follow C exactly (C `char` used as a
number is i8, as on x86 and wasm32 where char is signed). Each pointer
field gets the owning Rust type listed in OWN below; that table is the
whole of the representation change, and docs/representation.md explains it.
"""
import re, sys
draft = open(sys.argv[1]).read()
structs = {}
cur = None
for line in draft.split('\n'):
    m = re.match(r'^(struct|union) (\w+)\s+\[', line)
    if m:
        cur = m.group(2); structs[cur] = []; continue
    m = re.match(r'^    (\w+): (.+?),?$', line)
    if m and cur:
        structs[cur].append((m.group(1), m.group(2).rstrip(',')))
    if line.startswith('ALIASES'): break

ALIAS = {'TExtInflow': 'ExtInflow', 'TDwfInflow': 'DwfInflow', 'TTableEntry': 'TableEntry'}
SCALAR = {'int': 'i32', 'double': 'f64', 'float': 'f32', 'char': 'i8', 'schar': 'i8', 'long': 'i64',
          'DateTime': 'DateTime', 'uint': 'u32'}
# pointer fields: (struct, field) -> rust type
OWN = {
 ('TTable', 'ID'): 'Vec<u8>',
 ('TGage', 'ID'): 'Vec<u8>', ('TAquifer', 'ID'): 'Vec<u8>', ('TSnowmelt', 'ID'): 'Vec<u8>',
 ('TSubcatch', 'ID'): 'Vec<u8>', ('TPattern', 'ID'): 'Vec<u8>', ('TUnitHyd', 'ID'): 'Vec<u8>',
 ('TNode', 'ID'): 'Vec<u8>', ('TTransect', 'ID'): 'Vec<u8>', ('TStreet', 'ID'): 'Vec<u8>',
 ('TLink', 'ID'): 'Vec<u8>', ('TPollut', 'ID'): 'Vec<u8>', ('TLanduse', 'ID'): 'Vec<u8>',
 ('TLidProc', 'ID'): 'Vec<u8>',
 ('TFile', 'file'): 'Option<CFile>',
 ('TLandFactor', 'buildup'): 'Vec<f64>',
 ('TSubcatch', 'initBuildup'): 'Vec<f64>', ('TSubcatch', 'landFactor'): 'Vec<TLandFactor>',
 ('TSubcatch', 'groundwater'): 'Option<Box<TGroundwater>>',
 ('TSubcatch', 'gwLatFlowExpr'): 'Option<MathExpr>', ('TSubcatch', 'gwDeepFlowExpr'): 'Option<MathExpr>',
 ('TSubcatch', 'snowpack'): 'Option<Box<TSnowpack>>',
 ('TSubcatch', 'oldQual'): 'Vec<f64>', ('TSubcatch', 'newQual'): 'Vec<f64>',
 ('TSubcatch', 'pondedQual'): 'Vec<f64>', ('TSubcatch', 'totalLoad'): 'Vec<f64>',
 ('TTreatment', 'equation'): 'Option<MathExpr>',
 ('TNode', 'extInflow'): 'Vec<TExtInflow>', ('TNode', 'dwfInflow'): 'Vec<TDwfInflow>',
 ('TNode', 'rdiiInflow'): 'Option<TRdiiInflow>', ('TNode', 'treatment'): 'Vec<TTreatment>',
 ('TNode', 'oldQual'): 'Vec<f64>', ('TNode', 'newQual'): 'Vec<f64>',
 ('TOutfall', 'wRouted'): 'Vec<f64>',
 ('TStorage', 'exfil'): 'Option<Box<TExfil>>',
 ('TExfil', 'btmExfil'): 'Option<Box<TGrnAmpt>>', ('TExfil', 'bankExfil'): 'Option<Box<TGrnAmpt>>',
 ('TLink', 'inlet'): 'Option<usize>',
 ('TLink', 'oldQual'): 'Vec<f64>', ('TLink', 'newQual'): 'Vec<f64>', ('TLink', 'totalLoad'): 'Vec<f64>',
 ('TLanduse', 'buildupFunc'): 'Vec<TBuildup>', ('TLanduse', 'washoffFunc'): 'Vec<TWashoff>',
 ('TOutfallStats', 'totalLoad'): 'Vec<f64>',
 ('TLidProc', 'drainRmvl'): 'Vec<f64>',
 ('TLidRptFile', 'file'): 'Option<CFile>',
 ('TLidUnit', 'rptFile'): 'Option<Box<TLidRptFile>>',
}
NOTE = {
 ('TTable', 'firstEntry'): None, ('TTable', 'lastEntry'): None, ('TTable', 'thisEntry'): None,
 ('ExtInflow', 'next'): None, ('DwfInflow', 'next'): None, ('TableEntry', 'next'): None,
}
ORDER = ['TFile', 'TableEntry', 'TTable', 'TGage', 'TTemp', 'TWind', 'TSnow', 'TEvap', 'TAdjust', 'TEvent',
  'TAquifer', 'TGWaterStats', 'TGroundwater', 'TSnowmelt', 'TSnowpack', 'TSubarea', 'TLandFactor', 'TSubcatch',
  'TPattern', 'ExtInflow', 'DwfInflow', 'TRdiiInflow', 'TUnitHyd', 'TTreatment', 'TNode', 'TOutfall', 'TStorage',
  'TDivider', 'TXsect', 'TTransect', 'TStreet', 'TShape', 'TLink', 'TConduit', 'TPump', 'TOrifice', 'TWeir',
  'TOutlet', 'TPollut', 'TBuildup', 'TWashoff', 'TLanduse', 'TRptFlags', 'TRunoffTotals', 'TLoadingTotals',
  'TGwaterTotals', 'TRoutingTotals', 'TTimeStepStats', 'TRainStats', 'TSubcatchStats', 'TNodeStats',
  'TStorageStats', 'TOutfallStats', 'TPumpStats', 'TLinkStats', 'TMaxStats',
  'TSurfaceLayer', 'TPavementLayer', 'TSoilLayer', 'TStorageLayer', 'TDrainLayer', 'TDrainMatLayer',
  'TLidProc', 'TWaterBalance', 'TLidRptFile', 'TLidUnit', 'THorton', 'TGrnAmpt', 'TCurveNum', 'TExfil']
RENAME = {'type_0': 'type_'}

def rtype(sname, fname, t):
    if (sname, fname) in OWN: return OWN[(sname, fname)]
    t = t.strip()
    m = re.fullmatch(r'\[(.+); (\d+)\]', t)
    if m:
        inner = 'u8' if m.group(1).strip() == 'char' else rtype(sname, fname, m.group(1))
        return f'[{inner}; {m.group(2)}]'
    if t in SCALAR: return SCALAR[t]
    if t.startswith('*'): raise SystemExit(f'unmapped pointer {sname}.{fname}: {t}')
    return t

def maxarr(t):
    return max([int(x) for x in re.findall(r'; (\d+)\]', t)] or [0])

out = ['//! The shared data types of objects.h, infil.h, exfil.h and lid.h in safe Rust',
       '//! (generated by tools/skeleton/gen_objects.py, then reviewed).', '//!',
       '//! Field names, order and scalar types are C\'s. A C `char` holding a number',
       '//! is `i8` (char is signed on x86-64 and wasm32). Pointers became owners:',
       '//! `char* ID` is `Vec<u8>` (a model\'s names are bytes, not UTF-8); a',
       '//! `double*` array is `Vec<f64>`; a pointer that may be NULL is `Option<..>`;',
       '//! a linked list is a `Vec` in the order C walks it (element 0 is the head).',
       '//! `TTable` keeps its points in `entries`; C\'s cursor `thisEntry` is an index.', '',
       'use crate::cio::CFile;', 'use crate::mathexpr::MathExpr;', '', 'pub type DateTime = f64;', '']
for s in ORDER:
    fields = structs[s]
    rows = []
    has_owner = False; big = False
    for f, t in fields:
        if (s, f) in NOTE: continue
        rt = rtype(s, f, t)
        if any(k in rt for k in ('Vec<', 'Option<Box', 'Option<CFile', 'Option<MathExpr', 'Option<TRdii', 'Option<usize', 'CFile')):
            has_owner = True
        if maxarr(rt) > 32: big = True
        rows.append((RENAME.get(f, f), rt))
    name = 'TTableEntry' if s == 'TableEntry' else 'TExtInflow' if s == 'ExtInflow' else 'TDwfInflow' if s == 'DwfInflow' else s
    if s == 'TTable':
        rows.insert(rows.index(('file', 'TFile')), ('entries', 'Vec<TTableEntry>'))
        rows.insert(rows.index(('file', 'TFile')), ('thisEntry', 'Option<usize>'))
        has_owner = True
    copy_ok = not has_owner and all(r[1] not in ('TFile', 'TTransect') or s in () for r in rows)
    # a struct holding a non-Copy struct is not Copy
    nocopy_members = {'TFile', 'TTable', 'TSubcatch', 'TNode', 'TLink', 'TLanduse', 'TStreet', 'TLidProc',
                      'TLidRptFile', 'TLidUnit', 'TStorage', 'TExfil', 'TTreatment', 'TOutfall', 'TOutfallStats',
                      'TLandFactor', 'TGage'}
    if any(r[1] in nocopy_members for r in rows): copy_ok = False
    derives = ['Clone'] + (['Copy'] if copy_ok else []) + ([] if big or s == 'TFile' or name in ('TTable',) else ['Default'])
    if s in ('TFile', 'TLidRptFile'):
        derives = ['Default']
    if s == 'TTable':
        derives = ['Default']
    if s == 'TLidUnit':
        derives = ['Default']
    if big: derives = [d for d in derives if d != 'Default']
    if derives: out.append(f'#[derive({", ".join(derives)})]')
    out.append(f'pub struct {name} {{')
    for f, t in rows:
        out.append(f'    pub {f}: {t},')
    out.append('}')
    if big:
        out.append(f'impl Default for {name} {{')
        out.append('    fn default() -> Self {')
        out.append('        Self {')
        for f, t in rows:
            if re.fullmatch(r'\[.*\]', t):
                inner = t
                # nested array default
                m = re.fullmatch(r'\[\[(.+); (\d+)\]; (\d+)\]', t)
                if m:
                    z = '0' if m.group(1) in ('i32', 'i64', 'i8', 'u8') else '0.0'
                    out.append(f'            {f}: [[{z}; {m.group(2)}]; {m.group(3)}],')
                else:
                    m = re.fullmatch(r'\[(.+); (\d+)\]', t)
                    z = '0' if m.group(1) in ('i32', 'i64', 'i8', 'u8') else '0.0' if m.group(1) in ('f64', 'f32') else 'Default::default()'
                    out.append(f'            {f}: [{z}; {m.group(2)}],')
            else:
                out.append(f'            {f}: Default::default(),')
        out.append('        }')
        out.append('    }')
        out.append('}')
    out.append('')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('ok')

# helpers on TFile appended by hand-written code below
open(sys.argv[2], 'a').write('''
impl TFile {
    /// `fprintf(f.file, ...)`, `fputs`, `fwrite`: bytes to the open file.
    /// C would crash writing to a NULL `FILE*`; SWMM always checks first,
    /// so a write to an unopened TFile is dropped.
    #[inline]
    pub fn write_bytes(&mut self, b: &[u8]) {
        if let Some(f) = self.file.as_mut() {
            f.write_bytes(b);
        }
    }
    /// The open file. Panics where C would have dereferenced NULL.
    #[inline]
    pub fn f(&mut self) -> &mut CFile {
        self.file.as_mut().expect("I/O on a file that is not open")
    }
}

impl TLidRptFile {
    #[inline]
    pub fn write_bytes(&mut self, b: &[u8]) {
        if let Some(f) = self.file.as_mut() {
            f.write_bytes(b);
        }
    }
}
''')
