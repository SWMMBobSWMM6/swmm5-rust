#!/usr/bin/env python3
"""keywords.c -> keywords.rs: each NULL-terminated table becomes a slice
without the terminator (a Rust slice carries its length)."""
import re, sys
s = open(sys.argv[1], encoding='latin-1').read()
s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
s = re.sub(r'//[^\n]*', '', s)
out = ['//! The keyword tables of keywords.c (generated by tools/skeleton/gen_keywords.py).',
       '//! C ends each table with a NULL entry; a slice knows its length instead.', '',
       'use crate::text::*;', '']
for m in re.finditer(r'char\s*\*\s*(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;', s, flags=re.S):
    name, body = m.groups()
    items = [x.strip() for x in body.replace('\n', ' ').split(',') if x.strip()]
    term = items[-1] == 'NULL'
    if term: items = items[:-1]
    assert 'NULL' not in items, name
    conv = []
    for it in items:
        if it.startswith('"'):
            conv.append('b' + it)
        else:
            conv.append(it)
    if not term:
        out.append(f'/// (no NULL terminator in C: indexed only, never searched)')
    out.append(f'pub const {name}: &[&[u8]] = &[{", ".join(conv)}];')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(out) - 5, 'tables')
